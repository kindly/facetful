#!/usr/bin/env python3
"""Generate the search tokenizer's Unicode tables and their test fixtures.

  python3 scripts/gen-unicode-tables.py UCD_DIR

UCD_DIR holds UnicodeData.txt, NormalizationTest.txt and WordBreakTest.txt of
the Unicode version Rust's `char` methods implement (`char::UNICODE_VERSION`;
17.0.0 for Rust 1.97), from https://www.unicode.org/Public/<version>/ucd/
(WordBreakTest.txt is under auxiliary/). Writes:

- crates/facetful-engine/src/unicode_tables.rs: FOLD, each character whose
  full canonical decomposition is one character plus accents in U+0300-036F
  (or one character alone), mapped to that character; MARKS, the ranges of
  combining marks (general categories Mn, Mc, Me).
- crates/facetful-engine/tests/data/normalization.txt: NormalizationTest's
  character-by-character part, as source;NFC;NFD (hex code points);y|n,
  y where the tokenizer must give the same words for all three: the NFD is
  one character, not a mark or Hangul jamo, plus accents in U+0300-036F
  (other marks are kept, and nothing composes jamo or letter pairs).
- crates/facetful-engine/tests/data/wordbreak-apostrophes.txt: the
  WordBreakTest cases made only of ASCII letters, digits and apostrophes
  (U+0027, U+2019), with their UAX #29 words.
"""
import os
import sys

ACCENTS = range(0x300, 0x370)
root = os.path.join(os.path.dirname(__file__), "..")
ucd = sys.argv[1]

# UnicodeData: canonical decompositions and general categories
decomp, cat = {}, {}
first = None
for line in open(os.path.join(ucd, "UnicodeData.txt"), encoding="utf-8"):
    f = line.split(";")
    cp, name, gc, dm = int(f[0], 16), f[1], f[2], f[5]
    if name.endswith(", First>"):
        first = cp
        continue
    if name.endswith(", Last>"):
        for c in range(first, cp + 1):
            cat[c] = gc
        continue
    cat[cp] = gc
    if dm and not dm.startswith("<"):
        decomp[cp] = [int(x, 16) for x in dm.split()]


def full(cp):
    if cp not in decomp:
        return [cp]
    return [x for c in decomp[cp] for x in full(c)]


fold = []
for cp in sorted(decomp):
    rest = [c for c in full(cp) if c not in ACCENTS]
    if len(rest) == 1 and rest[0] != cp:
        fold.append((cp, rest[0]))

marks = []
for cp in sorted(c for c, g in cat.items() if g in ("Mn", "Mc", "Me")):
    if marks and marks[-1][1] == cp - 1:
        marks[-1][1] = cp
    else:
        marks.append([cp, cp])

version = open(os.path.join(ucd, "NormalizationTest.txt"), encoding="utf-8").readline().strip("# \n")
with open(os.path.join(root, "crates/facetful-engine/src/unicode_tables.rs"), "w") as out:
    out.write("// Generated by scripts/gen-unicode-tables.py from Unicode's UCD\n")
    out.write(f"// ({version.replace('NormalizationTest-', '').replace('.txt', '')}); do not edit. Unicode data is under the\n")
    out.write("// Unicode License v3 (crates/facetful-engine/tests/data/UNICODE-LICENSE).\n\n")
    out.write("/// Characters whose canonical decomposition is one character plus accents\n")
    out.write("/// in U+0300-036F (or that character alone), and that character.\n")
    out.write(f"pub(crate) static FOLD: [(u32, u32); {len(fold)}] = [\n")
    for i in range(0, len(fold), 6):
        out.write("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in fold[i : i + 6]) + "\n")
    out.write("];\n\n")
    out.write("/// Combining marks (general categories Mn, Mc, Me), as inclusive ranges.\n")
    out.write(f"pub(crate) static MARKS: [(u32, u32); {len(marks)}] = [\n")
    for i in range(0, len(marks), 6):
        out.write("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in marks[i : i + 6]) + "\n")
    out.write("];\n")

data = os.path.join(root, "crates/facetful-engine/tests/data")
os.makedirs(data, exist_ok=True)
part = None
with open(os.path.join(data, "normalization.txt"), "w") as out:
    out.write(f"# {version}, part 1 (character by character): source;NFC;NFD;same words\n")
    out.write("# Unicode data, Unicode License v3: see UNICODE-LICENSE\n")
    for line in open(os.path.join(ucd, "NormalizationTest.txt"), encoding="utf-8"):
        if line.startswith("@Part"):
            part = line.split()[0]
            continue
        if part != "@Part1" or line.startswith("#") or not line.strip():
            continue
        cols = line.split(";")[:3]
        nfd = [int(x, 16) for x in cols[2].split()]
        base = [c for c in nfd if c not in ACCENTS]
        same = len(base) == 1 and cat.get(base[0], "Cn")[0] != "M" and not 0x1100 <= base[0] <= 0x11FF
        out.write(";".join(cols + ["y" if same else "n"]) + "\n")

ok = set(range(0x30, 0x3A)) | set(range(0x41, 0x5B)) | set(range(0x61, 0x7B)) | {0x27, 0x2019}
wb_version = open(os.path.join(ucd, "WordBreakTest.txt"), encoding="utf-8").readline().strip("# \n")
with open(os.path.join(data, "wordbreak-apostrophes.txt"), "w") as out:
    out.write(f"# {wb_version}: cases of ASCII letters, digits and apostrophes;\n")
    out.write("# code points, then | and the UAX #29 segments (space separated)\n")
    out.write("# Unicode data, Unicode License v3: see UNICODE-LICENSE\n")
    for line in open(os.path.join(ucd, "WordBreakTest.txt"), encoding="utf-8"):
        test = line.split("#")[0].split()
        if not test:
            continue
        cps = [int(t, 16) for t in test if t not in ("÷", "×")]
        if not (any(c in (0x27, 0x2019) for c in cps) and all(c in ok for c in cps)):
            continue
        segs, cur = [], []
        for t in test[1:]:
            if t == "÷":
                segs.append(cur)
                cur = []
            elif t != "×":
                cur.append(int(t, 16))
        out.write(" ".join(f"{c:04X}" for c in cps) + " | " + " ".join("".join(chr(c) for c in s) for s in segs) + "\n")

print(f"FOLD {len(fold)} entries, MARKS {len(marks)} ranges; fixtures in {data}")
